# Logic Calculator using Python

def arithmetic_operations():
    print("\n--- Arithmetic Operations ---")

    try:
        num1 = float(input("Enter first number: "))
        num2 = float(input("Enter second number: "))

        print("\n1. Addition")
        print("2. Subtraction")
        print("3. Multiplication")
        print("4. Division")
        print("5. Modulus")
        print("6. Power")

        choice = input("Enter your choice: ")

        if choice == "1":
            print("Result:", num1 + num2)
        elif choice == "2":
            print("Result:", num1 - num2)
        elif choice == "3":
            print("Result:", num1 * num2)
        elif choice == "4":
            if num2 != 0:
                print("Result:", num1 / num2)
            else:
                print("Cannot divide by zero.")
        elif choice == "5":
            if num2 != 0:
                print("Result:", num1 % num2)
            else:
                print("Cannot find modulus with zero.")
        elif choice == "6":
            print("Result:", num1 ** num2)
        else:
            print("Invalid operation choice.")

    except ValueError:
        print("Please enter valid numbers.")


def comparison_operations():
    print("\n--- Comparison Operations ---")

    try:
        num1 = float(input("Enter first number: "))
        num2 = float(input("Enter second number: "))

        print("Greater than:", num1 > num2)
        print("Less than:", num1 < num2)
        print("Equal to:", num1 == num2)
        print("Not equal to:", num1 != num2)

    except ValueError:
        print("Please enter valid numbers.")


def logical_operations():
    print("\n--- Logical Operations ---")

    first = input("Enter first value (True/False): ").lower()
    second = input("Enter second value (True/False): ").lower()

    if first != "true" and first != "false":
        print("Invalid first value.")
        return

    if second != "true" and second != "false":
        print("Invalid second value.")
        return

    value1 = (first == "true")
    value2 = (second == "true")

    print("AND:", value1 and value2)
    print("OR:", value1 or value2)
    print("NOT first value:", not value1)
    print("NOT second value:", not value2)


def main():
    while True:
        print("\n--- Python Logic Calculator ---")
        print("1. Arithmetic Operations")
        print("2. Comparison Operations")
        print("3. Logical Operations")
        print("4. Exit")

        choice = input("Enter your choice: ")

        if choice == "1":
            arithmetic_operations()
        elif choice == "2":
            comparison_operations()
        elif choice == "3":
            logical_operations()
        elif choice == "4":
            print("Thank you for using the calculator!")
            break
        else:
            print("Invalid choice. Please try again.")

if __name__ == "__main__":
    main()